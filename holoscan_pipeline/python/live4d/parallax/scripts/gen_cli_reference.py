"""Generate the parallax command reference from the installed parsers."""
import argparse
import importlib
from pathlib import Path

TARGET = Path(__file__).resolve().parents[5] / "docs/parallax/CLI.md"


def _parsers():
    modules = ["offline", "tools.migrate_flags", "tools.simulate_4dstem", "tools.calibrate_parallax",
               "tools.repeat_dstream", "tools.refocus_dstream", "tools.replay_to_zmq",
               "tools.record_dstream", "tools.npy_to_dstream", "tools.make_dstream", "tools.dstream",
               "tools.detector_setup", "streaming.web", "examples.viewer", "examples.probe",
               "examples.plot_result", "scripts.bench_accumulator", "scripts.compare_accumulate",
               "scripts.session_report"]
    return [(name, importlib.import_module("live4d.parallax." + name).build_parser()) for name in modules]


def render():
    lines = ["# Parallax command reference", "", "Generated by `python -m live4d.parallax.scripts.gen_cli_reference`.",
             "Live acquisition uses `python -m live4d --config pipeline.yaml`; see [the guide](GUIDE.md).", ""]
    def table(parser):
        rows = ["| Parameter | Default | Description |", "| --- | --- | --- |"]
        for action in parser._actions:
            if isinstance(action, argparse._HelpAction):
                continue
            if isinstance(action, argparse._SubParsersAction):
                for name, sub in action.choices.items():
                    rows.extend(["", f"**{name}**", "", *table(sub)])
                continue
            label = ", ".join(action.option_strings) or action.dest
            default = "required" if action.required else str(action.default)
            import sys
            if default == sys.executable:
                default = "current Python"
            help_text = " ".join((action.help or "").split()).replace("|", "\\|")
            rows.append(f"| `{label}` | `{default}` | {help_text} |")
        return rows
    for name, parser in _parsers():
        lines += [f"## `{parser.prog}`", "", *table(parser), ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != text:
            raise SystemExit(f"{TARGET} is stale")
    else:
        TARGET.write_text(text)


if __name__ == "__main__":
    main()
