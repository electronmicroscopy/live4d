def _parsers():
    from realtime_stem.apps import run
    from realtime_stem.processing import registry

    out = [("run", run.build_parser(registry.get("parallax")))]
    for mod in ("tools.simulate_4dstem", "tools.replay_to_zmq", "tools.record_dstream",
                "tools.npy_to_dstream", "tools.make_dstream", "tools.dstream", "tools.detector_setup",
                "examples.viewer", "examples.probe", "examples.plot_result"):
        out.append((mod, importlib.import_module(mod).build_parser()))
    spec = importlib.util.spec_from_file_location(
        "bench_accumulator", REPO / "scripts" / "bench_accumulator.py")
    bench = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bench)
    out.append(("bench", bench.build_parser()))
    return out


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _default(action) -> str:
    if isinstance(action, (argparse._StoreTrueAction, argparse._StoreFalseAction)):
        return "flag"
    d = action.default
    if d is None or d is argparse.SUPPRESS or (action.required and d is None):
        return "required" if action.required else ""
    if isinstance(d, (list, tuple)):
        return "`" + " ".join(str(v) for v in d) + "`"
    return f"`{d}`"


def _actions(group):
    return [a for a in group._group_actions
            if not isinstance(a, (argparse._HelpAction, argparse._SubParsersAction))]


def _table(parser, actions) -> list[str]:
    fmt = parser._get_formatter()
    plain = argparse.HelpFormatter(parser.prog)
    rows = ["| parameter | default | description |", "|---|---|---|"]
    for a in actions:
        inv = fmt._format_action_invocation(a)
        if not a.option_strings and a.choices:
            inv = f"{a.dest} {{{','.join(map(str, a.choices))}}}"
        rows.append(f"| `{_cell(inv)}` | {_default(a)} | {_cell(plain._expand_help(a))} |")
    return rows


def _render_parser(key, parser) -> list[str]:
    lines = [f"## `{parser.prog}`", "", INTROS[key], ""]
    lines += ["```text", parser.format_usage().strip(), "```", ""]
    for group in parser._action_groups:
        acts = _actions(group)
        if acts:
            title = {"positional arguments": "arguments", "options": "general"}.get(
                group.title, group.title)
            lines += [f"**{title}**", ""] + _table(parser, acts) + [""]
    for a in parser._actions:                       # sub-commands (tools.dstream info)
        if isinstance(a, argparse._SubParsersAction):
            for name, sub in a.choices.items():
                lines += [f"**`{name}` sub-command**", ""] + _table(sub, _actions(
                    sub._action_groups[0]) + _actions(sub._action_groups[1])) + [""]
    return lines


def _render_scripts() -> list[str]:
    lines = ["## Demo scripts", "",
             "Configured by environment variables (shown with their defaults) and one optional "
             "positional argument, the capture to replay.", ""]
    pat = re.compile(r'^(\w+)="\$\{\1:-(.*?)\}"\s*(?:#\s*(.*))?$')
    for script, what in (("scripts/run_local_demo.sh",
                          "No Docker, no NVIDIA GPU: feeder → `run.py --ingest python` → viewer. "
                          "Simulates `out/sim256.dstream` on first use."),
                         ("scripts/run_replay_demo.sh",
                          "The same through the Docker image and the Holoscan ingest.")):
        lines += [f"**`{script} [CAPTURE]`** — {what}", "",
                  "| variable | default | meaning |", "|---|---|---|"]
        for raw in (REPO / script).read_text().splitlines():
            m = pat.match(raw.strip())
            if m:
                lines.append(f"| `{m[1]}` | `{_cell(m[2])}` | {_cell(m[3] or '')} |")
        lines.append("")
    return lines


def _render_notebook() -> list[str]:
    from realtime_stem.streaming.notebook import LiveView

    sig = inspect.signature(LiveView.__init__)
    what = {
        "endpoint": "the `run.py --live-endpoint` to subscribe to",
        "cmap": "matplotlib colormap of every panel",
        "high_pass_sigma": "Gaussian high-pass in pixels for display (0 = off)",
        "panel_size": "inches per panel",
        "history": "frames kept for `snapshot_at` / `save_gif` (0 = none); each costs "
                   "C × Ny × Nx × 4 bytes",
    }
    lines = ["## Notebook: `realtime_stem.streaming.notebook.LiveView`", "",
             "Not a command, but the notebook entry point (`examples/live_view.ipynb`): "
             "`LiveView(endpoint, ...)`, then `view.start()` (receive in the background), "
             "`await view.wait_final()`, `view.snapshot_at(progress, scan_pass=None)`, "
             "`view.save_gif(path)`, `view.latest`, `view.history`, `view.stop()`.", "",
             "| parameter | default | meaning |", "|---|---|---|"]
    for name, prm in sig.parameters.items():
        if name == "self":
            continue
        default = "required" if prm.default is inspect.Parameter.empty else f"`{prm.default!r}`"
        lines.append(f"| `{name}` | {default} | {what[name]} |")
    return lines + [""]


def render() -> str:
    os.environ["COLUMNS"] = "100"                 # deterministic usage wrapping
    parsers = _parsers()
    index = "\n".join(f"| [`{p.prog}`](#{_anchor(p.prog)}) | {SHORT[k]} |" for k, p in parsers)
    index += "\n| [demo scripts](#demo-scripts) | `run_local_demo.sh`, `run_replay_demo.sh` |"
    index += ("\n| [notebook view](#notebook-realtime_stemstreamingnotebooklive" "view) | "
              "`LiveView` for Jupyter |")
    lines = [HEADER.format(index=index)]
    for key, parser in parsers:
        lines += _render_parser(key, parser)
    lines += _render_scripts() + _render_notebook()
    return "\n".join(lines).rstrip() + "\n"


def _anchor(title: str) -> str:
    """GitHub's heading anchor for a `## \\`title\\`` heading."""
    return re.sub(r"[^a-z0-9 _-]", "", title.lower()).replace(" ", "-")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="Exit 1 if docs/CLI.md is out of date.")
    args = p.parse_args()
    text = render()
    if args.check:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is out of date: run python scripts/gen_cli_reference.py")
            raise SystemExit(1)
        print(f"{TARGET} is up to date")
        return
    TARGET.write_text(text)
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
